def setup_table(ws, head, widths, nrows, *, date_cols=(), text_cols=(), num_cols=(), calc_cols=()):
    ws.append(head)
    for j, name in enumerate(head, start=1):
        c = ws.cell(1, j)
        c.font, c.alignment = HEAD_FONT, Alignment(wrap_text=True, vertical="center")
        c.fill = CALC_FILL if name in calc_cols else HEAD_FILL
        ws.column_dimensions[get_column_letter(j)].width = widths.get(name, 14)
    ws.row_dimensions[1].height = 36
    ws.freeze_panes = "A2"
    for name, fmt in [(n, mock.DATE_FMT) for n in date_cols] + [(n, "@") for n in text_cols] + list(num_cols):
        col = head.index(name) + 1
        for r in range(2, nrows + 2):
            ws.cell(r, col).number_format = fmt
    for name in calc_cols:
        col = head.index(name) + 1
        for r in range(2, nrows + 2):
            ws.cell(r, col).fill = CALC_FILL


def add_list(ws, head, name, values, nrows, title, msg):
    col = L(head, name)
    dv = DataValidation(type="list", formula1='"' + ",".join(values) + '"', allow_blank=True,
                        showErrorMessage=True, errorStyle="warning", errorTitle=title, error=msg,
                        showInputMessage=False)
    dv.add(f"{col}2:{col}{nrows + 1}")
    ws.add_data_validation(dv)


def add_rule(ws, head, names, nrows, kind, op, f1, f2=None, msg=""):
    dv = DataValidation(type=kind, operator=op, formula1=f1, formula2=f2, allow_blank=True,
                        showErrorMessage=True, errorStyle="warning", errorTitle="ตรวจค่าที่กรอก", error=msg)
    for name in names:
        col = L(head, name)
        dv.add(f"{col}2:{col}{nrows + 1}")
    ws.add_data_validation(dv)


